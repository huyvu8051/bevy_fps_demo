#!/usr/bin/env python3
"""Run in a NORMAL terminal (not Unreal's Python console) — plain Python,
no `unreal` module needed. Converts unreal_export_level_layout.py's JSON
output into a RON file this project's `shared::read_ron_data_file!` macro
can load, spawned in Bevy via a generic fn mirroring
spawn_item_gallery_test_props's pattern (see
crates/client/src/unreal_prop_layout.rs).

Usage:
    python3 scripts/unreal_layout_json_to_ron.py \\
        /tmp/unreal_level_export/level_layout.json \\
        crates/client/assets/data/map12_prop_layout.ron \\
        --mesh-dir props/unreal_import

The --mesh-dir value is where you'll have imported+re-exported each FBX
as glTF (import into Blender, clean up if needed, export .glb into
crates/client/assets/<mesh-dir>/) — this script just points every entry
at "<mesh-dir>/<mesh_name>.glb" by naming convention, it does NOT touch
the actual mesh files.

COORDINATE CONVERSION CAVEAT (read this before trusting the output):
Unreal is centimeters, Z-up, left-handed. Bevy/glTF is meters, Y-up,
right-handed. Position converts cleanly (swap Y/Z, negate one axis, scale
by 0.01) — that part is solid. Rotation is the fragile part: a simple
per-axis Euler angle swap is only an approximation of the real
change-of-basis (which technically needs a quaternion conjugation, not
component reordering) — it happens to work for pure yaw (rotation around
the up axis, the most common case for props placed upright on a floor),
but ROLL/PITCH ON A TILTED PROP MAY COME OUT WRONG. Verify visually:
pick one prop with a non-zero rotation, compare how it looks in Unreal
vs. Bevy after import, and adjust the rotation formula below if it's
off — don't trust the whole batch blind.
"""

import argparse
import json
import os


def convert_position(location):
    x, y, z = location
    # cm -> m, swap Y/Z (Z-up -> Y-up), negate Z (left-handed -> right-handed)
    return (x * 0.01, z * 0.01, -y * 0.01)


def convert_rotation_euler_deg(rotation_roll_pitch_yaw):
    # See the module docstring's caveat — this is an approximation, solid
    # for pure yaw, unverified for combined roll+pitch+yaw.
    roll, pitch, yaw = rotation_roll_pitch_yaw
    return (pitch, -yaw, roll)


def convert_scale(scale):
    x, y, z = scale
    return (x, z, y)  # scale has no handedness to flip, just the Y/Z swap


def mesh_glb_path(mesh_package_path, mesh_dir):
    mesh_name = mesh_package_path.split("/")[-1].split(".")[0]
    return f"{mesh_dir}/{mesh_name}.glb"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("input_json", help="Path to unreal_export_level_layout.py's level_layout.json output")
    parser.add_argument("output_ron", help="Path to write the .ron file")
    parser.add_argument("--mesh-dir", default="props/unreal_import",
                         help="Asset-relative dir the converted .glb files will live in (default: props/unreal_import)")
    args = parser.parse_args()

    with open(args.input_json) as f:
        layout = json.load(f)

    lines = [
        "// Generated by scripts/unreal_layout_json_to_ron.py from an Unreal Editor",
        f"// level export ({os.path.basename(args.input_json)}) — see that script's",
        "// own docstring for the coordinate-conversion caveat (rotation is an",
        "// approximation, verified for pure yaw only). Loaded via",
        "// shared::read_ron_data_file! and spawned by",
        "// crates/client/src/unreal_prop_layout.rs's spawn_unreal_prop_layout.",
        "[",
    ]
    for entry in layout:
        pos = convert_position(entry["location"])
        rot = convert_rotation_euler_deg(entry["rotation"])
        scale = convert_scale(entry["scale"])
        mesh = mesh_glb_path(entry["mesh"], args.mesh_dir)
        lines.append(
            f'    (mesh: "{mesh}", position: ({pos[0]:.4f}, {pos[1]:.4f}, {pos[2]:.4f}), '
            f"rotation_euler_deg: ({rot[0]:.4f}, {rot[1]:.4f}, {rot[2]:.4f}), "
            f"scale: ({scale[0]:.4f}, {scale[1]:.4f}, {scale[2]:.4f})),"
        )
    lines.append("]")
    lines.append("")

    with open(args.output_ron, "w") as f:
        f.write("\n".join(lines))

    unique_meshes = sorted({mesh_glb_path(e["mesh"], args.mesh_dir) for e in layout})
    print(f"Wrote {len(layout)} placements to {args.output_ron}")
    print(f"References {len(unique_meshes)} unique .glb paths — make sure each of these actually exists:")
    for m in unique_meshes:
        print(f"  crates/client/assets/{m}")


if __name__ == "__main__":
    main()
